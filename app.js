function onBobotChanged() {
  const p = parseInt(document.getElementById('inpBobotP').value || 0, 10);
  const tgs = parseInt(document.getElementById('inpBobotTGS').value || 0, 10);
  const kuis = parseInt(document.getElementById('inpBobotKuis').value || 0, 10);
  const uts = parseInt(document.getElementById('inpBobotUTS').value || 0, 10);
  const uas = parseInt(document.getElementById('inpBobotUAS').value || 0, 10);

  const total = p + tgs + kuis + uts + uas;
  const badge = document.getElementById('bobotBadge');
  if (badge) {
    if (total === 100) {
      badge.className = 'bobot-badge valid';
      badge.innerText = `Total: ${total}% (Valid)`;
    } else {
      badge.className = 'bobot-badge invalid';
      badge.innerText = `Total: ${total}% (Wajib 100%)`;
    }
  }

  updateContractPreview();
}

