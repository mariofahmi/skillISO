function initSimulator() {
  populateCourseSelect(COURSES_DATA);
  const selectElem = document.getElementById('courseSelect');
  if (selectElem) {
    selectElem.value = currentCourseIndex;
    loadCourseToSimulator(currentCourseIndex);
  }
}

function populateCourseSelect(courseList) {
  const selectElem = document.getElementById('courseSelect');
  if (!selectElem) return;

  selectElem.innerHTML = courseList.map(c => {
    const originalIndex = COURSES_DATA.indexOf(c);
    return `<option value="${originalIndex}">${c.no}. ${c.name} (${c.sks} SKS • Sem ${c.sem} • ${c.code})</option>`;
  }).join('');
}

function onSelectCourse(idx) {
  currentCourseIndex = parseInt(idx, 10);
  loadCourseToSimulator(currentCourseIndex);
  const c = COURSES_DATA[currentCourseIndex];
  showToast(`Memuat kontrak: ${c.name}`);
}

function filterSimSem(semKey, btn) {
  document.querySelectorAll('.semester-chips-row .sem-chip').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');

  let filtered = COURSES_DATA;
  if (semKey !== 'all') {
    filtered = COURSES_DATA.filter(c => c.sem === parseInt(semKey, 10));
  }
  populateCourseSelect(filtered);

  if (filtered.length > 0) {
    const firstIdx = COURSES_DATA.indexOf(filtered[0]);
    document.getElementById('courseSelect').value = firstIdx;
    loadCourseToSimulator(firstIdx);
  }
}

